// A project's handwritten instruction content is its root host instruction
// files outside aiwf's managed blocks, the project router, and the
// documents the router links to. The names and readers below define that
// set once for every rule that judges or measures it.
const (
	// ClaudeFile is Claude Code's root instruction file.
	ClaudeFile = "CLAUDE.md"
	// AgentsFile is Codex's root instruction file.
	AgentsFile = "AGENTS.md"
	// RouterFile is the handwritten project router.
	RouterFile = ".guidance/project.md"
	// OwnedRecordFile records the guidance outputs aiwf owns.
	OwnedRecordFile = ownedFile
)

// The aiwf:guidance block wraps the import of aiwf's guidance fragment in
// CLAUDE.md and the rendered fragment itself in AGENTS.md.
const (
	GuidanceStartMarker  = "<!-- aiwf:guidance:START - DO NOT EDIT, regenerated by aiwf update -->"
	GuidanceEndMarker    = "<!-- aiwf:guidance:END -->"
	GuidanceMarkerPrefix = "<!-- aiwf:guidance:"
)

// GuidanceMarkers returns the start and end markers of the aiwf:guidance
// block and the prefix every marker of that block family carries, in the
// shape pathutil.ManagedBlockSpan takes.
func GuidanceMarkers() (start, end, prefix string) {
	return GuidanceStartMarker, GuidanceEndMarker, GuidanceMarkerPrefix
}

// ManagedBlockMarkers returns the marker sets of aiwf's managed blocks in a
// host instruction file: the aiwf:guidance block and the routing block.
func ManagedBlockMarkers() []func() (start, end, prefix string) {
	return []func() (string, string, string){GuidanceMarkers, RouteMarkers}
}

// HandwrittenText is a host instruction file with aiwf's managed blocks
// removed. Each block family is read strictly, as pathutil.ManagedBlockSpan
// reads it: where a family's markers are malformed — a stray marker of the
// family included — the file has no block of that family aiwf can own, and
// that block's text stays handwritten; the other family is still removed.
func HandwrittenText(content string) string {
	for _, markers := range ManagedBlockMarkers() {
		startMarker, endMarker, prefix := markers()
		start, end, err := pathutil.ManagedBlockSpan(content, startMarker, endMarker, prefix)
		if err != nil || start < 0 {
			continue
		}
		content = content[:start] + content[end:]
	}
	return content
}

// RoutedDocuments returns the repository-relative markdown documents the
// router links to, resolved as ResolveReference describes.
func RoutedDocuments(router string) []string {
	var out []string
	for _, target := range MarkdownLinks(router) {
		if p, ok := ResolveReference(RouterFile, target); ok && strings.HasSuffix(p, ".md") {
			out = append(out, p)
		}
	}
	return out
}

// OwnedOutputs reads the owned-output record and returns the outputs it
// lists. Only a path shaped like one aiwf owns counts, so a record cannot
// list a file of its own to carry it; a record that does not parse lists
// nothing.
func OwnedOutputs(record string) map[string]bool {
	owned := map[string]bool{}
	var listed map[string]string
	if json.Unmarshal([]byte(record), &listed) == nil {
		for p := range listed {
			if ValidOwnedPath(p) {
				owned[p] = true
			}
		}
	}
	return owned
}

// HandwrittenDocuments returns the documents the router links to that are
// handwritten instruction content: every routed document except an output
// aiwf owns, which is generated, and the host files and the router, which
// are instruction files by name.
func HandwrittenDocuments(router string, owned map[string]bool) []string {
	var out []string
	for _, p := range RoutedDocuments(router) {
		if !owned[p] && p != ClaudeFile && p != AgentsFile && p != RouterFile {
			out = append(out, p)
		}
	}
	return out
}

// MarkdownLinks returns the destinations of a document's links as
// CommonMark reads them: inline, reference-style, with or without a title,
// in angle brackets. Images and autolinks are not references to read.
func MarkdownLinks(doc string) []string {
	src := []byte(doc)
	var out []string
	root := goldmark.New().Parser().Parse(text.NewReader(src))
	// The walker never returns an error: the callback has no error path.
	_ = ast.Walk(root, func(n ast.Node, entering bool) (ast.WalkStatus, error) {
		if link, ok := n.(*ast.Link); ok && entering {
			out = append(out, string(link.Destination))
		}
		return ast.WalkContinue, nil
	})
	return out
}

// ResolveReference turns a reference made from the document at doc into a
// repository path. A leading slash is the repository root, as it is on the
// forge; anything else resolves against the document's directory. The
// anchor and query are dropped and percent-escapes decoded. A reference
// with a scheme, a bare anchor, or one leaving the repository is not a
// repository path.
func ResolveReference(doc, target string) (string, bool) {
	target, _, _ = strings.Cut(target, "#")
	target, _, _ = strings.Cut(target, "?")
	if target == "" || strings.Contains(target, ":") {
		return "", false
	}
	if decoded, err := url.PathUnescape(target); err == nil {
		target = decoded
	}
	var p string
	if rooted, ok := strings.CutPrefix(target, "/"); ok {
		p = path.Clean(rooted)
	} else {
		p = path.Clean(path.Join(path.Dir(doc), target))
	}
	if p == "." || p == ".." || strings.HasPrefix(p, "../") {
		return "", false
	}
	return p, true
}
